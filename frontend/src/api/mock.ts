interface MockRun {
  id: string
  title: string
  createdAt: number
}

const runs = new Map<string, MockRun>()

export function isMockId(id: string): boolean {
  return id.startsWith(MOCK_PREFIX)
}

export function createMockAnalysis(input: Pick<CreateAnalysisInput, 'title'>): AnalysisCreated {
  const id = `${MOCK_PREFIX}${Date.now().toString(36)}`
  const createdAt = Date.now()
  runs.set(id, {
    id,
    title: input.title?.trim() || 'Демо: реорганизация блока эксплуатации сети',
    createdAt,
  })
  return { id, status: 'queued', created_at: new Date(createdAt).toISOString() }
}

export function getMockAnalysis(id: string): Analysis {
  let run = runs.get(id)
  if (!run) {
    // Reloaded page or shared link: show the finished demo immediately.
    run = { id, title: 'Демо: реорганизация блока эксплуатации сети', createdAt: 0 }
    runs.set(id, run)
  }
  const elapsed = Date.now() - run.createdAt
  const base = {
    id: run.id,
    title: run.title,
    created_at: new Date(run.createdAt || Date.now()).toISOString(),
  }

  if (elapsed < QUEUE_MS) {
    return {
      ...base,
      status: 'queued',
      progress: 0,
      current_step: 'В очереди',
      steps: STEP_DEFS.map((s) => ({ ...s, status: 'pending' })),
    }
  }

  const running = elapsed - QUEUE_MS
  const total = STEP_MS * STEP_DEFS.length
  if (running < total) {
    const active = Math.floor(running / STEP_MS)
    return {
      ...base,
      status: 'processing',
      progress: Math.min(99, Math.round((running / total) * 100)),
      current_step: STEP_DEFS[active].title,
      steps: STEP_DEFS.map((s, i) => ({
        ...s,
        status: i < active ? 'completed' : i === active ? 'processing' : 'pending',
      })),
    }
  }

  return {
    ...base,
    status: 'completed',
    progress: 100,
    current_step: 'Готово',
    steps: STEP_DEFS.map((s) => ({ ...s, status: 'completed' })),
    summary: {
      before_functions: 40,
      after_functions: 44,
      unchanged: 31,
      lost: 3,
      added: 5,
      moved: 2,
      changed: 4,
      duplicates: 2,
      high_risk: 3,
    },
    findings: FINDINGS,
    conclusion: CONCLUSION,
    warnings: [
      'Демонстрационные данные: результат сформирован локально, без обращения к серверу анализа.',
      'Документ «Оргструктура_2026.docx» не содержит номеров страниц — ссылки указаны по пунктам.',
    ],
  }
}

